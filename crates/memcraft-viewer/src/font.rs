/// The glyph of `c`; anything outside printable ASCII shows as `?`.
fn glyph(c: char) -> &'static [u8; 8] {
    let i = (c as usize).wrapping_sub(' ' as usize);
    GLYPHS.get(i).unwrap_or(&GLYPHS['?' as usize - ' ' as usize])
}

/// Whether the editor may type `c`: what the font has.
pub fn is_typable(c: char) -> bool {
    (' '..='~').contains(&c)
}

/// How many glyphs fit on a line.
pub const LINE_CHARS: usize = (WIDTH + 1) / ADVANCE;

/// Draws four centred lines as RGBA, black on transparent, `WIDTH x HEIGHT`
/// pixels, row 0 on top. Minecraft's formatting codes (`§` and the character
/// after it) are not drawn.
pub fn render(lines: &[String; 4]) -> Vec<u8> {
    let mut rgba = vec![0u8; WIDTH * HEIGHT * 4];
    for (n, line) in lines.iter().enumerate() {
        let text = strip_formatting(line);
        let chars: Vec<char> = text.chars().take(LINE_CHARS).collect();
        let width = (chars.len() * ADVANCE).saturating_sub(ADVANCE - GLYPH);
        let (left, top) = ((WIDTH - width) / 2, (HEIGHT - 4 * LINE) / 2 + n * LINE);
        for (i, &c) in chars.iter().enumerate() {
            for (row, bits) in glyph(c).iter().enumerate() {
                for col in (0..GLYPH).filter(|col| bits >> (GLYPH - 1 - col) & 1 != 0) {
                    let at = ((top + row) * WIDTH + left + i * ADVANCE + col) * 4;
                    rgba[at..at + 4].copy_from_slice(&[0, 0, 0, 255]);
                }
            }
        }
    }
    rgba
}

/// `text` without `§x` formatting codes.
fn strip_formatting(text: &str) -> String {
    let mut out = String::new();
    let mut chars = text.chars();
    while let Some(c) = chars.next() {
        if c == '§' {
            chars.next();
        } else {
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lines(a: &str, b: &str, c: &str, d: &str) -> [String; 4] {
        [a, b, c, d].map(String::from)
    }

    fn set(rgba: &[u8], x: usize, y: usize) -> bool {
        rgba[(y * WIDTH + x) * 4 + 3] != 0
    }

    #[test]
    fn a_line_is_drawn_centred_on_its_own_row_band() {
        let none = render(&lines("", "", "", ""));
        assert!(none.iter().all(|&b| b == 0));
        // "I" is a bar in the middle of its 5 px: columns 2 of 0..5, in rows 0-6.
        let rgba = render(&lines("", "I", "", ""));
        let on: Vec<(usize, usize)> = (0..HEIGHT).flat_map(|y| (0..WIDTH).map(move |x| (x, y))).filter(|&(x, y)| set(&rgba, x, y)).collect();
        assert!(!on.is_empty());
        // The second line's band is rows 14..22 (4 px margin, 10 per line).
        assert!(on.iter().all(|&(_, y)| (14..22).contains(&y)), "{on:?}");
        // One glyph, 5 px wide, in the middle of the 96 px.
        assert!(on.iter().all(|&(x, _)| (45..50).contains(&x)), "{on:?}");
    }

    #[test]
    fn long_lines_are_clipped_to_the_face_and_other_characters_become_question_marks() {
        let long = "W".repeat(40);
        let rgba = render(&lines(&long, "é", "?", "§4a§rb"));
        assert!((0..HEIGHT).any(|y| set(&rgba, 0, y)) || (0..HEIGHT).any(|y| set(&rgba, 1, y)));
        // `é` and `?` look alike, so do `§4a§rb` and `ab`.
        let band = |n: usize| -> Vec<u8> { (0..8).flat_map(|y| rgba[((4 + 10 * n + y) * WIDTH) * 4..][..WIDTH * 4].to_vec()).collect() };
        assert_eq!(band(1), band(2));
        assert_eq!(band(3), render(&lines("", "", "", "ab"))[((4 + 30) * WIDTH) * 4..][..8 * WIDTH * 4]);
    }

    #[test]
    fn every_glyph_fits_five_columns() {
        for (i, g) in GLYPHS.iter().enumerate() {
            assert!(g.iter().all(|&row| row < 32), "{:?}", (b' ' + i as u8) as char);
            assert!(i == 0 || g.iter().any(|&row| row != 0), "{:?} is blank", (b' ' + i as u8) as char);
        }
    }
}
