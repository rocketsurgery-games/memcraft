//! A small bitmap font for sign text: monospaced 5x8 glyphs (caps seven rows
//! tall, a row below for descenders) for printable ASCII, drawn into an RGBA
//! image of black text on a transparent background.
//!
//! A sign's face is 96x48 text pixels (one block wide, half a block tall) and
//! holds four lines 10 px apart, so a line fits 16 glyphs of 6 px.

/// The text image of a sign, in pixels.
