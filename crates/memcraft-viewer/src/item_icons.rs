//! Which atlas tile shows a Pocket Edition item (not a block) held in an item
//! frame. The icons are Pixel Perfection's item textures, see
//! `assets/ATTRIBUTION.md`; items without one are left out.

use crate::blocks::{atlas::tile as t, Tile};

/// The icon of item `id` with damage value `damage`, for item ids of 256 and up.
pub fn icon(id: i16, damage: i16) -> Option<Tile> {
    if id == 351 {
        return DYES.get(usize::try_from(damage).ok()?).copied();
    }
    ICONS.binary_search_by_key(&id, |&(i, _)| i).ok().map(|i| ICONS[i].1)
}

