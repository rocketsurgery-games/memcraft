//! Paintings and item frames, drawn once at startup.
//!
//! Paintings are entity records of the world's columns (Bedrock NBT, entity
//! id 83); item frames are the block entities named `ItemFrame` on a block of
//! id 199 (which the mesher draws as air). Both are static: they do not
//! collide, cannot be targeted and stay put when the wall behind them is
//! edited.
//!
//! The painting pictures and the frame and item textures are Pixel
//! Perfection by XSSheep (CC BY-SA 4.0), see `assets/ATTRIBUTION.md`.

use bevy::asset::RenderAssetUsages;
