/// The picture every painting is cut from, generated by `build.rs`.
mod picture {
    include!(concat!(env!("OUT_DIR"), "/paintings.rs"));
}

/// Pixels per block in the painting picture.
const PAINTING_PX: u32 = 16;
/// A painting is a slab this thick, and an item frame a plate of the same.
const THICKNESS: f32 = 1.0 / 16.0;
/// How far the background and the item float in front of an item frame's
/// face, so they win the depth test.
const LAYER: f32 = 0.003;

/// The painting motifs by name: `[x, y, width, height]` in pixels of the
/// picture (the size in blocks is that over 16).
const MOTIFS: [(&str, [u32; 4]); 26] = [
    ("Kebab", [0, 0, 16, 16]),
    ("Aztec", [16, 0, 16, 16]),
    ("Alban", [32, 0, 16, 16]),
    ("Aztec2", [48, 0, 16, 16]),
    ("Bomb", [64, 0, 16, 16]),
    ("Plant", [80, 0, 16, 16]),
    ("Wasteland", [96, 0, 16, 16]),
    ("Pool", [0, 32, 32, 16]),
    ("Courbet", [32, 32, 32, 16]),
    ("Sea", [64, 32, 32, 16]),
    ("Sunset", [96, 32, 32, 16]),
    ("Creebet", [128, 32, 32, 16]),
    ("Wanderer", [0, 64, 16, 32]),
    ("Graham", [16, 64, 16, 32]),
    ("Match", [0, 128, 32, 32]),
    ("Bust", [32, 128, 32, 32]),
    ("Stage", [64, 128, 32, 32]),
    ("Void", [96, 128, 32, 32]),
    ("SkullAndRoses", [128, 128, 32, 32]),
    ("Wither", [160, 128, 32, 32]),
    ("Fighters", [0, 96, 64, 32]),
    ("Pointer", [0, 192, 64, 64]),
    ("Pigscene", [64, 192, 64, 64]),
    ("BurningSkull", [128, 192, 64, 64]),
    ("Skeleton", [192, 64, 64, 48]),
    ("DonkeyKong", [192, 112, 64, 48]),
];

/// A horizontal facing, numbered as Java does: 0 faces +z, 1 -x, 2 -z, 3 +x.
/// Hanging things face away from the wall they hang on.
type Facing = u8;

/// The unit step `(x, z)` a facing looks along.
fn step(facing: Facing) -> (i32, i32) {
    match facing & 3 {
        0 => (0, 1),
        1 => (-1, 0),
        2 => (0, -1),
        _ => (1, 0),
    }
}

#[derive(Debug, Clone, PartialEq)]
struct Painting {
    /// The centre of the painting's slab, in world coordinates.
    centre: [f32; 3],
    facing: Facing,
    /// Size in blocks.
    size: [f32; 2],
    /// Where the picture is, in pixels: `[x, y, width, height]`.
    picture: [u32; 4],
}

#[derive(Debug, Clone, PartialEq)]
struct ItemFrame {
    /// The block the frame is in.
    cell: [i32; 3],
    facing: Facing,
    /// The held item's atlas tile and its tint, if it has an icon.
    icon: Option<(Tile, [f32; 3])>,
}

/// Every painting in the world's entity records.
fn paintings(world: &PeWorld) -> Vec<Painting> {
    world
        .columns
        .values()
        .flat_map(|col| &col.entities)
        // Newer saves keep flags above the low byte of the id.
        .filter(|e| e.get("id").and_then(Tag::as_i64).is_some_and(|id| id & 0xff == 83))
        .filter_map(|e| {
            let pos: Vec<f32> = e.get("Pos")?.as_list()?.iter().filter_map(Tag::as_f64).map(|v| v as f32).collect();
            let motif = e.get("Motive")?.as_str()?;
            let &(_, picture) = MOTIFS.iter().find(|(name, _)| *name == motif)?;
            Some(Painting {
                centre: pos.try_into().ok()?,
                facing: e.get("Direction")?.as_i64()? as Facing & 3,
                size: [picture[2], picture[3]].map(|px| (px / PAINTING_PX) as f32),
                picture,
            })
        })
        .collect()
}

/// Every item frame: an `ItemFrame` block entity on an item frame block.
fn item_frames(world: &PeWorld) -> Vec<ItemFrame> {
    world
        .columns
        .values()
        .flat_map(|col| &col.block_entities)
        .filter(|be| be.get("id").and_then(Tag::as_str) == Some("ItemFrame"))
        .filter_map(|be| {
            let cell = ["x", "y", "z"].map(|k| be.get(k).and_then(Tag::as_i64).map(|v| v as i32));
            let cell = [cell[0]?, cell[1]?, cell[2]?];
            let (id, data) = world.block(cell[0], cell[1], cell[2]);
            (id == 199).then_some(ItemFrame {
                cell,
                // Block data 0..3: faces east, west, south, north.
                facing: [3, 1, 0, 2][(data & 3) as usize],
                icon: be.get("Item").and_then(held_icon),
            })
        })
        .collect()
}

/// The atlas tile and tint that show an item stack: a block's side, or an
/// item's icon. `None` for an empty frame or an item without one.
fn held_icon(item: &Tag) -> Option<(Tile, [f32; 3])> {
    let id = item.get("id")?.as_i64()?;
    let damage = item.get("Damage").and_then(Tag::as_i64).unwrap_or(0);
    match id {
        1..=255 => {
            let look = blocks::look(id as u8, damage as u8);
            (look.shape != Shape::Air).then_some((look.tiles[4], look.color))
        }
        256.. => Some((item_icons::icon(i16::try_from(id).ok()?, damage as i16)?, [1.0; 3])),
        _ => None,
    }
}

/// A coordinate frame for something hanging on a wall: `u` runs to the right
/// as seen from the front, `v` up and `w` out of the wall, around `centre`.
struct Wall {
    centre: [f32; 3],
    right: [f32; 3],
    forward: [f32; 3],
}

impl Wall {
    fn new(centre: [f32; 3], facing: Facing) -> Self {
        let (x, z) = step(facing);
        // Seen from the front (looking along -forward), right is forward
        // turned a quarter: +x for a wall facing +z.
        Self { centre, right: [z as f32, 0.0, -x as f32], forward: [x as f32, 0.0, z as f32] }
    }

    fn point(&self, [u, v, w]: [f32; 3]) -> [f32; 3] {
        std::array::from_fn(|i| self.centre[i] + self.right[i] * u + self.forward[i] * w + if i == 1 { v } else { 0.0 })
    }

    /// The face of the box `lo..hi` (in `u, v, w`) on the positive or
    /// negative side of `axis`, with its corners counter-clockwise seen from
    /// outside, starting at the bottom left for the front face, and its normal.
    fn face(&self, lo: [f32; 3], hi: [f32; 3], axis: usize, positive: bool) -> ([[f32; 3]; 4], [f32; 3]) {
        // (u, v, w) is right-handed, so b x c = axis for the cyclic successors.
        let (b, c) = match (axis, positive) {
            (2, true) => (0, 1),
            (0, true) => (1, 2),
            (1, true) => (2, 0),
            (2, false) => (1, 0),
            (0, false) => (2, 1),
            _ => (0, 2),
        };
        let fixed = if positive { hi[axis] } else { lo[axis] };
        let corners = [(lo[b], lo[c]), (hi[b], lo[c]), (hi[b], hi[c]), (lo[b], hi[c])].map(|(pb, pc)| {
            let mut p = [0.0; 3];
            (p[axis], p[b], p[c]) = (fixed, pb, pc);
            self.point(p)
        });
        let direction = [self.right, [0.0, 1.0, 0.0], self.forward][axis];
        (corners, direction.map(|d| if positive { d } else { -d }))
    }

    /// Adds one face of a box to `out`.
    fn quad(&self, out: &mut MeshData, (lo, hi): ([f32; 3], [f32; 3]), (axis, positive): (usize, bool), color: [f32; 4], uv: [f32; 4]) {
        let (corners, normal) = self.face(lo, hi, axis, positive);
        out.quad(corners, normal, color, uv);
    }
}

/// Brightness of the painting or frame, from the air it faces and the side it
/// is seen from, as for block faces (see `mesh::FACES`).
fn shade(wall: &Wall, sky: f32) -> [f32; 4] {
    let side = if wall.forward[0] != 0.0 { 0.8 } else { 0.65 };
    [side * sky, side * sky, side * sky, 1.0]
}

/// The paintings' front faces, textured from the painting picture.
fn painting_mesh(paintings: &[Painting], light: &dyn Fn(i32, i32, i32) -> f32) -> MeshData {
    let mut mesh = MeshData::default();
    let (w, h) = (picture::WIDTH as f32, picture::HEIGHT as f32);
    for p in paintings {
        let wall = Wall::new(p.centre, p.facing);
        let [hw, hh] = p.size.map(|s| s / 2.0);
        // Seen from the front, the slab's surface is half its thickness out.
        let cell = wall.point([0.0, 0.0, 0.5]).map(|v| v.floor() as i32);
        let color = shade(&wall, light(cell[0], cell[1], cell[2]));
        let [x, y, pw, ph] = p.picture.map(|v| v as f32);
        let uv = [x / w, y / h, (x + pw) / w, (y + ph) / h];
        wall.quad(&mut mesh, ([-hw, -hh, -THICKNESS / 2.0], [hw, hh, THICKNESS / 2.0]), (2, true), color, uv);
    }
    mesh
}

/// The item frames: a wooden plate against the wall, a lining and the item.
fn frame_mesh(frames: &[ItemFrame], light: &dyn Fn(i32, i32, i32) -> f32) -> MeshData {
    let mut mesh = MeshData::default();
    let whole = [0.0, 0.0, 1.0, 1.0];
    for f in frames {
        let wall = Wall::new(f.cell.map(|v| v as f32 + 0.5), f.facing);
        let color = shade(&wall, light(f.cell[0], f.cell[1], f.cell[2]));
        // The plate is 12 px square and touches the wall, which is half a block back.
        let (back, front) = (-0.5, -0.5 + THICKNESS);
        let plate = ([-0.375, -0.375, back], [0.375, 0.375, front]);
        let wood = tile_rect(t::ITEMFRAME_BORDER, whole);
        for (axis, positive) in [(2, true), (0, true), (0, false), (1, true), (1, false)] {
            wall.quad(&mut mesh, plate, (axis, positive), color, wood);
        }
        let mut layer = |half: f32, depth: f32, tile: Tile, color: [f32; 4]| {
            let w = front + depth;
            wall.quad(&mut mesh, ([-half, -half, w], [half, half, w]), (2, true), color, tile_rect(tile, whole));
        };
        layer(0.3125, LAYER, t::ITEMFRAME_BACKGROUND, color);
        if let Some((tile, tint)) = f.icon {
            layer(0.25, 2.0 * LAYER, tile, [color[0] * tint[0], color[1] * tint[1], color[2] * tint[2], 1.0]);
        }
    }
    mesh
}

/// The painting picture as a GPU image, sampled without filtering.
fn picture_image() -> Image {
    let size = Extent3d { width: picture::WIDTH, height: picture::HEIGHT, depth_or_array_layers: 1 };
    let mut image = Image::new(size, TextureDimension::D2, picture::RGBA.to_vec(), TextureFormat::Rgba8UnormSrgb, RenderAssetUsages::RENDER_WORLD);
    image.sampler = ImageSampler::nearest();
    image
}

/// Spawns every painting and item frame of the world.
pub fn spawn(
    mut commands: Commands,
    map: Res<WorldMap>,
    block_materials: Res<BlockMaterials>,
    mut meshes: ResMut<Assets<Mesh>>,
    mut materials: ResMut<Assets<StandardMaterial>>,
    mut images: ResMut<Assets<Image>>,
) {
    let light = |x, y, z| map.light(x, y, z);
    let paintings = paintings(map.world());
    let frames = item_frames(map.world());
    let picture = materials.add(StandardMaterial {
        base_color: Color::WHITE,
        base_color_texture: Some(images.add(picture_image())),
        unlit: true,
        ..default()
    });
    commands.spawn((Mesh3d(meshes.add(to_bevy(painting_mesh(&paintings, &light)))), MeshMaterial3d(picture)));
    // Item icons have transparent corners, so frames use the cutout pass.
    commands.spawn((Mesh3d(meshes.add(to_bevy(frame_mesh(&frames, &light)))), MeshMaterial3d(block_materials.cutout.clone())));
    info!(
        "drew {} paintings and {} item frames ({} with an item icon)",
        paintings.len(),
        frames.len(),
        frames.iter().filter(|f| f.icon.is_some()).count()
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> PeWorld {
        PeWorld::open_dir(concat!(env!("CARGO_MANIFEST_DIR"), "/../../worlds/My World")).unwrap()
    }

    #[test]
    fn the_sample_world_has_its_paintings_and_item_frames() {
        let world = sample();
        assert_eq!(paintings(&world).len(), 157);
        let frames = item_frames(&world);
        assert_eq!(frames.len(), 9);
        assert_eq!(frames.iter().filter(|f| f.icon.is_some()).count(), 8);
    }

    #[test]
    fn paintings_hang_on_walls_facing_open_air() {
        let world = sample();
        for p in paintings(&world) {
            let wall = Wall::new(p.centre, p.facing);
            let [w, h] = p.size;
            for i in 0..w as i32 {
                for j in 0..h as i32 {
                    let (u, v) = (i as f32 + 0.5 - w / 2.0, j as f32 + 0.5 - h / 2.0);
                    let cell = |depth: f32| {
                        let [x, y, z] = wall.point([u, v, depth]).map(|c| c.floor() as i32);
                        world.block(x, y, z)
                    };
                    let behind = cell(-0.5);
                    let front = cell(0.5);
                    assert_ne!(blocks::look(behind.0, behind.1).shape, Shape::Air, "{p:?} cell {i},{j} has no wall");
                    assert_ne!(blocks::look(front.0, front.1).shape, Shape::Cube, "{p:?} cell {i},{j} is inside a wall");
                }
            }
        }
    }

    #[test]
    fn item_frames_hang_on_a_block() {
        let world = sample();
        for f in item_frames(&world) {
            let (dx, dz) = step(f.facing);
            let behind = world.block(f.cell[0] - dx, f.cell[1], f.cell[2] - dz);
            assert_ne!(blocks::look(behind.0, behind.1).shape, Shape::Air, "{f:?} has no block behind it");
        }
    }

    #[test]
    fn faces_look_outwards_and_the_front_is_the_right_way_up() {
        for facing in 0..4 {
            let wall = Wall::new([10.0, 20.0, 30.0], facing);
            let (x, z) = step(facing);
            let out = Vec3::new(x as f32, 0.0, z as f32);
            let (lo, hi) = ([-1.0, -1.0, 0.0], [1.0, 1.0, 0.1]);
            for (axis, positive) in [(0, true), (0, false), (1, true), (1, false), (2, true), (2, false)] {
                let (c, n) = wall.face(lo, hi, axis, positive);
                let c = c.map(Vec3::from);
                // Counter-clockwise from outside: the winding normal agrees with the face's.
                assert!((c[1] - c[0]).cross(c[2] - c[0]).dot(Vec3::from(n)) > 0.0, "face {axis} {positive} winds away from its normal");
            }
            // The front is upright, and its right side is the viewer's right: the
            // direction `out` turns to when seen from above, clockwise.
            let (c, n) = wall.face(lo, hi, 2, true);
            let c = c.map(Vec3::from);
            assert_eq!(Vec3::from(n), out);
            assert!(c[0].y < c[3].y && c[1].y < c[2].y);
            assert_eq!(c[1] - c[0], 2.0 * Vec3::new(out.z, 0.0, -out.x));
        }
    }

    #[test]
    fn every_motif_lies_inside_the_picture() {
        for (name, [x, y, w, h]) in MOTIFS {
            assert!(x + w <= picture::WIDTH && y + h <= picture::HEIGHT, "{name} is outside the picture");
            assert!(w % PAINTING_PX == 0 && h % PAINTING_PX == 0, "{name} is not a whole number of blocks");
        }
    }
}
