const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } })
  const logs = []
  page.on('console', m => logs.push(`[${m.type()}] ${m.text()}`.slice(0, 300)))
  page.on('pageerror', e => logs.push('[pageerror] ' + e.message.slice(0, 300)))
  page.on('dialog', async d => { logs.push('[dialog] ' + d.message().slice(0, 300)); await d.accept() })
  const zip = require('fs').readFileSync('my-world.zip')
  await page.route('https://memcraft.invalid/**', r => r.fulfill({ status: 200, body: zip, headers: { 'Content-Type': 'application/zip', 'Access-Control-Allow-Origin': '*' } }))
  const url = 'https://mcraft.fun/?map=' + encodeURIComponent('https://memcraft.invalid/my-world.zip')
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 })
  await page.waitForFunction(() => document.body.innerText.includes('Click to capture'), null, { timeout: 120000 }).catch(() => {})
  await page.waitForTimeout(8000)
  const pos = () => page.evaluate(() => { const b = window.bot; return b && b.entity ? [b.entity.position.x, b.entity.position.y, b.entity.position.z, b.entity.yaw, b.entity.pitch, b.game.gameMode].map(String).join(' ') : 'no bot' })
  logs.push('[pos] spawn ' + await pos())
  for (const [name, x, y, z, yaw, pitch] of [JSON.parse(process.env.VIEW)]) {
    await page.evaluate(() => { try { window.bot.creative.startFlying() } catch (e) {} })
    await page.evaluate(([x, y, z, yaw, pitch]) => window.bot.chat(`/tp wanderer ${x} ${y} ${z}`), [x, y, z, yaw, pitch])
    await page.waitForTimeout(1500)
    await page.evaluate(() => { const b = window.bot; try { b.creative.startFlying() } catch (e) {} })
    await page.evaluate(([yaw, pitch]) => window.bot.look(yaw, pitch, true), [yaw, pitch])
    await page.waitForTimeout(15000)
    logs.push('[pos] ' + name + ' ' + await pos())
    await page.screenshot({ path: `${process.env.OUT}/view-${name}.png` })
  }
  console.log(logs.filter(l => !/\[debug\]|\[verbose\]/.test(l)).slice(-60).join('\n'))
  await browser.close()
})().catch(e => { console.error(e); process.exit(1) })
